package boxPush3d.physics;

public class Box {
	
	public final double x, y, z, xSize, ySize, zSize;
	
	public Box(double x, double y, double z, double xSize, double ySize, double zSize)
	{
		this.x = x;
		this.y = y;
		this.z = z;
		this.xSize = xSize;
		this.ySize = ySize;
		this.zSize = zSize;
	}
}